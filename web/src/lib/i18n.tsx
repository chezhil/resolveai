const DICTS: Record<LangId, Dict> = { en, hi, kn, ta, te, mr, bn };

interface I18n {
  lang: LangId;
  setLang: (l: LangId) => void;
  t: (key: string) => string;
}

const Ctx = createContext<I18n>({ lang: "en", setLang: () => {}, t: (k) => en[k] ?? k });

const KEY = "resolveai.lang";

function initial(): LangId {
  try {
    const saved = localStorage.getItem(KEY) as LangId | null;
    if (saved && DICTS[saved]) return saved;
  } catch {
    // storage blocked: fall through
  }
  const nav = (navigator.language || "en").slice(0, 2) as LangId;
  return DICTS[nav] ? nav : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangId>(initial);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang: (l) => {
        setLangState(l);
        try {
          localStorage.setItem(KEY, l);
        } catch {
          // ignore
        }
      },
      t: (k) => DICTS[lang][k] ?? en[k] ?? k,
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
